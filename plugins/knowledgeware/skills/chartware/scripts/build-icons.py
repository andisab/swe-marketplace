#!/usr/bin/env python3
"""build-icons.py — assemble templates/svg/icons.svg, the currentColor icon sprite chartware diagrams use.

Sources (both fetched with npm; neither is vendored here beyond the sprite this script writes):
  @tabler/icons   outline icons, 24-unit grid, stroke currentColor   MIT  (Paweł Kuna)
  simple-icons    brand marks, 24-unit grid, fill currentColor         CC0 1.0 (brand trademarks stay with their owners)

    npm install --prefix /tmp/icons @tabler/icons@3.49.0 simple-icons@16.35.0
    python3 scripts/build-icons.py /tmp/icons/node_modules

Edit the two lists below to add or remove icons, run the script, and commit the sprite and references/icons.md
it rewrites. Each symbol is `cwi-<name>`; diagrams copy the symbols they use into their own <defs>.
"""
import os
import re
import sys

TABLER = [
    # infrastructure
    "server", "server-2", "database", "cloud", "cloud-upload", "cpu", "container", "topology-star-3",
    "network", "router", "world", "api", "plug-connected", "stack-2", "box", "package",
    # clients and people
    "browser", "device-mobile", "device-desktop", "user", "users", "robot", "mail", "message-circle", "bell",
    # security
    "lock", "key", "shield-check", "eye", "fingerprint",
    # files and code
    "file-text", "folder", "code", "terminal-2", "git-branch", "git-pull-request", "settings", "tool",
    # state and flow
    "clock", "calendar", "check", "x", "alert-triangle", "info-circle", "refresh", "bolt", "filter",
    "search", "upload", "download", "arrow-right", "arrows-exchange", "link", "chart-bar", "chart-line",
    "report-analytics", "flag", "bookmark", "star", "trash", "edit", "copy", "external-link",
]
SIMPLE = [
    "github", "gitlab", "docker", "kubernetes", "terraform", "postgresql", "mysql", "mongodb", "redis",
    "apachekafka", "elasticsearch", "snowflake", "databricks", "grafana", "prometheus", "python",
    "typescript", "javascript", "nodedotjs", "react", "rust", "go", "googlecloud", "anthropic",
    "googlegemini", "huggingface", "jupyter", "linux", "nginx", "cloudflare", "vercel", "figma", "notion",
]


def read_svg(path):
    return open(path, encoding="utf-8").read()


def tabler_symbol(name, svg):
    m = re.search(r"<svg[^>]*>(.*)</svg>", svg, re.S)
    body = m.group(1) if m else ""
    body = re.sub(r'\s*<path stroke="none" d="M0 0h24v24H0z" fill="none"\s*/>', "", body)  # the invisible bounds rect
    body = re.sub(r"\n\s*", " ", body).strip()
    return (f'  <symbol id="cwi-{name}" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="1.75" '
            f'stroke-linecap="round" stroke-linejoin="round">{body}</symbol>')


def simple_symbol(name, svg):
    title = re.search(r"<title>(.*?)</title>", svg)
    pm = re.search(r'<path d="([^"]+)"', svg)
    path = pm.group(1) if pm else ""
    return f'  <symbol id="cwi-{name}" viewBox="0 0 24 24" fill="currentColor"><title>{title.group(1) if title else name}</title><path d="{path}"/></symbol>'


def main():
    if len(sys.argv) != 2:
        print(__doc__)
        sys.exit(1)
    nm = sys.argv[1]
    here = os.path.dirname(os.path.abspath(__file__))
    out_svg = os.path.join(here, "..", "templates", "svg", "icons.svg")
    out_md = os.path.join(here, "..", "references", "icons.md")
    def version(pkg):
        m = re.search(r'"version":\s*"([^"]+)"', read_svg(os.path.join(nm, *pkg, "package.json")))
        return m.group(1) if m else "?"
    tver = version(["@tabler", "icons"])
    sver = version(["simple-icons"])
    symbols, rows, missing = [], [], []
    for n in TABLER:
        p = os.path.join(nm, "@tabler", "icons", "icons", "outline", f"{n}.svg")
        if not os.path.exists(p):
            missing.append(("tabler", n)); continue
        symbols.append(tabler_symbol(n, read_svg(p)))
        rows.append((f"cwi-{n}", "outline", "Tabler Icons"))
    for n in SIMPLE:
        p = os.path.join(nm, "simple-icons", "icons", f"{n}.svg")
        if not os.path.exists(p):
            missing.append(("simple-icons", n)); continue
        symbols.append(simple_symbol(n, read_svg(p)))
        rows.append((f"cwi-{n}", "brand", "Simple Icons"))
    sprite = (f'<!-- chartware icon sprite — generated by scripts/build-icons.py; do not edit by hand.\n'
              f'     {len([r for r in rows if r[1] == "outline"])} outline icons from Tabler Icons {tver} (MIT, © Paweł Kuna) and\n'
              f'     {len([r for r in rows if r[1] == "brand"])} brand marks from Simple Icons {sver} (CC0 1.0; trademarks belong to their owners).\n'
              f'     Every symbol draws in currentColor on a 24-unit grid. Use inside a diagram:\n'
              f'       copy the <symbol> into the diagram\'s <defs>, then <use href="#cwi-server" x=".." y=".." width="20" height="20"/>\n'
              f'       with color set on the <use> or an ancestor, e.g. style="color:var(-\u200b-cw-muted)" without the\n'
              f'       zero-width space (an XML comment may not contain two hyphens in a row). See references/icons.md. -->\n'
              f'<svg xmlns="http://www.w3.org/2000/svg" style="display:none" aria-hidden="true">\n' + "\n".join(symbols) + "\n</svg>\n")
    open(out_svg, "w", encoding="utf-8").write(sprite)
    md = ["# Icons for SVG diagrams\n",
          f"`templates/svg/icons.svg` holds {len(rows)} `<symbol>` definitions on a 24-unit grid, all drawn in `currentColor`: "
          f"{len([r for r in rows if r[1] == 'outline'])} outline icons from [Tabler Icons](https://tabler.io/icons) {tver} (MIT) and "
          f"{len([r for r in rows if r[1] == 'brand'])} brand marks from [Simple Icons](https://simpleicons.org) {sver} (CC0 1.0; the trademarks belong to their owners, so use a brand mark only to denote that product). "
          "`scripts/build-icons.py` regenerates the sprite from the npm packages; edit its two lists to add icons.\n",
          "## Using an icon in a diagram\n",
          "Copy the `<symbol>` you need from the sprite into the diagram's own `<defs>` (inline SVG can't reference another file's symbols, and `<img>`-embedded SVG can't reach the page's), then place it with `<use>`. Colour comes from `currentColor`, so set `color` on the `<use>` or its group and it follows the theme:\n",
          "```svg\n<defs>\n  <symbol id=\"cwi-database\" viewBox=\"0 0 24 24\" fill=\"none\" stroke=\"currentColor\" ...>…</symbol>\n</defs>\n"
          "<g class=\"node-icon\" style=\"color:var(--cw-muted)\">\n  <use href=\"#cwi-database\" x=\"112\" y=\"100\" width=\"20\" height=\"20\"/>\n</g>\n```\n",
          "Sizes: 20 units beside a 13px label inside a card, 16 in a chip, 28–32 as the only content of a compact node. Keep the icon in the muted tone and let the stroke of the node carry identity; an icon in the accent counts as one of the two accent roles. One outline icon per node at most, and never an outline icon next to a brand mark in the same node.\n",
          "The lint (`scripts/svg-lint.py`) reports a `<use>` whose `href` names a symbol the file doesn't define.\n",
          "## Catalog\n", "| Symbol | Kind | Source |\n|---|---|---|"]
    md += [f"| `{i}` | {k} | {s} |" for i, k, s in rows]
    if missing:
        md.append("\nNot found in the installed packages (check the name on the source site): " + ", ".join(f"{s}/{n}" for s, n in missing))
    open(out_md, "w", encoding="utf-8").write("\n".join(md) + "\n")
    print(f"wrote {out_svg} ({len(rows)} symbols) and {out_md}")
    if missing:
        print("missing:", ", ".join(f"{s}/{n}" for s, n in missing))


if __name__ == "__main__":
    main()
